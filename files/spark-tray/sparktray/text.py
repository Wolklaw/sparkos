TABLES = {'en': EN, 'fr': FR}
LANG = ui_language()
_T = TABLES[LANG]


def t(key: str, **kw) -> str:
    text = _T.get(key) or EN.get(key) or key
    return text.format(**kw) if kw else text


def check_tables() -> List[str]:
    """Problems between the two tables: a missing sentence, or a blank like {name} that one
    language has and the other doesn't. Empty when they match."""
    problems = []
    for key in sorted(set(EN) | set(FR)):
        if key not in EN or key not in FR:
            problems.append(f"{key}: only in {'en' if key in EN else 'fr'}")
            continue
        if sorted(re.findall(r'\{(\w+)\}', EN[key])) != sorted(re.findall(r'\{(\w+)\}', FR[key])):
            problems.append(f"{key}: the blanks differ")
    return problems
