TABLES = {'en': EN, 'fr': FR}
LANG = ui_language()
_T = TABLES[LANG]


def t(key: str, **kw) -> str:
    n = kw.get('n')
    if isinstance(n, int):
        singular = n == 1 or (LANG == 'fr' and n == 0)
        if singular and (key + '.1') in EN:
            key = key + '.1'
    text = _T.get(key) or EN.get(key) or key
    return text.format(**kw) if kw else text
